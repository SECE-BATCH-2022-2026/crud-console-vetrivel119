package org.bm;

public class Student {
    private int id;
    private int rollNo;
    private String name;
    private String emailId;
    private String deptId;

    public Student(int id, int rollNo, String name, String emailId, String deptId) {
        this.id = id;
        this.rollNo = rollNo;
        this.name = name;
        this.emailId = emailId;
        this.deptId = deptId;
    }
}
